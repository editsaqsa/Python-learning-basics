#slicing
my_list = ["apple", "banana", "cherry", "date", "elderberry"]
print("original list:", my_list)
print("elements from index 1 to 3:", my_list[1:4])
print("elements from the beginning to index 2:", my_list[:3])
print("elements from index 2 to the end:", my_list[2:5])
print("elements from index 1 to 4 with a step of 2:", my_list[1:4:2])